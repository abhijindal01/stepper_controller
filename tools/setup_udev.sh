#!/usr/bin/env bash
#
# Create the stable serial-port names the web app expects:
#
#       MOTOR 1  ->  /dev/stepper_a
#       MOTOR 2  ->  /dev/stepper_b
#
# Uses physical USB socket ID_PATH (or distinct board serials when unique)
# so identical clone Arduinos on Raspberry Pi 4B never collide onto the
# same symlink.
#
# Usage:
#     sudo bash tools/setup_udev.sh
#     sudo MOTOR1_DEV=/dev/ttyACM0 MOTOR2_DEV=/dev/ttyACM1 bash tools/setup_udev.sh
#

set -u

OUT="/etc/udev/rules.d/99-stepper-controllers.rules"

while [ $# -gt 0 ]; do
    case "$1" in
        --out) OUT="$2"; shift 2 ;;
        -h|--help) sed -n '2,16p' "$0"; exit 0 ;;
        *) echo "Unknown option: $1"; exit 1 ;;
    esac
done

DEVICES=()

for dev in /dev/ttyUSB* /dev/ttyACM*; do
    [ -e "$dev" ] || continue
    DEVICES+=("$dev")
done

if [ ${#DEVICES[@]} -eq 0 ]; then
    echo "No /dev/ttyUSB* or /dev/ttyACM* device found."
    echo "Plug in BOTH Arduino boards and run this again."
    exit 1
fi

describe() {
    local dev="$1"
    local props path serial id_path kernel vendor model

    props=$(udevadm info -q property -n "$dev" 2>/dev/null)

    serial=$(echo "$props"  | sed -n 's/^ID_SERIAL_SHORT=//p')
    id_path=$(echo "$props" | sed -n 's/^ID_PATH=//p')
    vendor=$(echo "$props"  | sed -n 's/^ID_VENDOR_ID=//p')
    model=$(echo "$props"   | sed -n 's/^ID_MODEL_ID=//p')

    path=$(udevadm info -q path -n "$dev" 2>/dev/null)

    # Use tail -1 so on Raspberry Pi 4B we get the leaf socket (1-1.2), NOT the root hub (1-1)
    kernel=$(echo "$path" | tr '/' '\n' | grep -E '^[0-9]+-[0-9]+(\.[0-9]+)*$' | tail -1)

    printf '%s|%s|%s|%s|%s|%s' "$dev" "${serial:-}" "${id_path:-}" "${kernel:-}" "${vendor:-}" "${model:-}"
}

echo
echo "USB serial devices found:"
echo

INFO=()
i=0

for dev in "${DEVICES[@]}"; do
    i=$((i + 1))
    info=$(describe "$dev")
    INFO+=("$info")

    IFS='|' read -r _d serial id_path kernel vendor model <<< "$info"

    echo "  [$i] $dev"
    echo "      usb id  : ${vendor}:${model}"
    echo "      serial  : ${serial:-<none>}"
    echo "      id_path : ${id_path:-<none>}"
    echo "      socket  : ${kernel:-<unknown>}"
    echo
done

index_of_dev() {
    local want="$1" idx
    for idx in "${!DEVICES[@]}"; do
        if [ "${DEVICES[$idx]}" = "$want" ]; then
            echo $((idx + 1))
            return 0
        fi
    done
    return 1
}

A_CHOICE=""
B_CHOICE=""

if [ -n "${MOTOR1_DEV:-}" ]; then
    A_CHOICE=$(index_of_dev "$MOTOR1_DEV") || { echo "MOTOR1_DEV=$MOTOR1_DEV was not found."; exit 1; }
fi

if [ -n "${MOTOR2_DEV:-}" ]; then
    B_CHOICE=$(index_of_dev "$MOTOR2_DEV") || { echo "MOTOR2_DEV=$MOTOR2_DEV was not found."; exit 1; }
fi

if [ -z "$A_CHOICE" ] || [ -z "$B_CHOICE" ]; then
    if [ ! -t 0 ]; then
        echo "No terminal to ask on - set MOTOR1_DEV and MOTOR2_DEV instead:"
        echo "  sudo MOTOR1_DEV=/dev/ttyACM0 MOTOR2_DEV=/dev/ttyACM1 bash tools/setup_udev.sh"
        exit 1
    fi

    if [ -z "$A_CHOICE" ]; then
        read -r -p "Which board drives MOTOR 1 (/dev/stepper_a)? [1-$i, default 1] " A_CHOICE
        A_CHOICE=${A_CHOICE:-1}
    fi

    if [ -z "$B_CHOICE" ]; then
        read -r -p "Which board drives MOTOR 2 (/dev/stepper_b)? [1-$i, default 2] " B_CHOICE
        B_CHOICE=${B_CHOICE:-2}
    fi
fi

valid_choice() {
    [[ "$1" =~ ^[0-9]+$ ]] && [ "$1" -ge 1 ] && [ "$1" -le "$i" ]
}

if ! valid_choice "$A_CHOICE" || ! valid_choice "$B_CHOICE"; then
    echo "Invalid selection (choose between 1 and $i)." >&2
    exit 1
fi

if [ "$A_CHOICE" = "$B_CHOICE" ]; then
    echo "Error: MOTOR 1 and MOTOR 2 cannot be assigned to the same USB device." >&2
    exit 1
fi

IFS='|' read -r A_DEV A_SERIAL A_IDPATH A_KERNEL _a1 _a2 <<< "${INFO[$((A_CHOICE - 1))]}"
IFS='|' read -r B_DEV B_SERIAL B_IDPATH B_KERNEL _b1 _b2 <<< "${INFO[$((B_CHOICE - 1))]}"

echo
echo "  MOTOR 1 -> $A_DEV -> /dev/stepper_a"
echo "  MOTOR 2 -> $B_DEV -> /dev/stepper_b"
echo

# Only use ATTRS{serial} if BOTH boards have non-empty AND distinct serials
USE_SERIAL=0
if [ -n "$A_SERIAL" ] && [ -n "$B_SERIAL" ] && [ "$A_SERIAL" != "$B_SERIAL" ]; then
    USE_SERIAL=1
fi

rule_for() {
    local dev="$1" serial="$2" id_path="$3" kernel="$4" link="$5"

    if [ "$USE_SERIAL" = "1" ] && [ -n "$serial" ]; then
        echo "SUBSYSTEM==\"tty\", ATTRS{serial}==\"$serial\", SYMLINK+=\"$link\", MODE=\"0666\""
    elif [ -n "$id_path" ]; then
        echo "SUBSYSTEM==\"tty\", ENV{ID_PATH}==\"$id_path\", SYMLINK+=\"$link\", MODE=\"0666\""
    elif [ -n "$kernel" ]; then
        echo "SUBSYSTEM==\"tty\", KERNELS==\"$kernel\", SYMLINK+=\"$link\", MODE=\"0666\""
    else
        echo "Could not build a rule for $dev." >&2
        return 1
    fi
}

TMP=$(mktemp)

{
    echo "# Generated by tools/setup_udev.sh on $(date)"
    echo "#"
    echo "#   MOTOR 1 -> /dev/stepper_a   ($A_DEV)"
    echo "#   MOTOR 2 -> /dev/stepper_b   ($B_DEV)"
    echo
    rule_for "$A_DEV" "$A_SERIAL" "$A_IDPATH" "$A_KERNEL" "stepper_a"
    rule_for "$B_DEV" "$B_SERIAL" "$B_IDPATH" "$B_KERNEL" "stepper_b"
} > "$TMP"

cat "$TMP"
echo

if ! cp "$TMP" "$OUT" 2>/dev/null; then
    FALLBACK="udev/99-stepper-controllers.generated.rules"
    cp "$TMP" "$FALLBACK"
    echo "Could not write $OUT (run as root?) - wrote $FALLBACK instead."
    echo "Install it with:"
    echo "  sudo cp $FALLBACK $OUT"
    echo "  sudo rm -f /dev/stepper_a /dev/stepper_b"
    echo "  sudo udevadm control --reload-rules && sudo udevadm trigger --subsystem-match=tty"
    rm -f "$TMP"
    exit 0
fi

rm -f "$TMP"
echo "Wrote $OUT"

if command -v udevadm >/dev/null 2>&1 && [ "$(id -u)" = "0" ]; then
    rm -f /dev/stepper_a /dev/stepper_b
    udevadm control --reload-rules
    udevadm trigger --subsystem-match=tty
    sleep 1
    echo
    echo "Result:"
    ls -l /dev/stepper_a /dev/stepper_b 2>/dev/null \
        || echo "  (unplug and replug the boards if symlinks have not appeared yet)"
fi
